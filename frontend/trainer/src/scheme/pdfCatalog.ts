/** Соответствие PDF-тега → id узла на мнемосхеме (для объединённых блоков). */
export function pdfTagToSchemeId(tag: string): string {
  const t = tag
    .toUpperCase()
    .replace('H-', 'N-')
    .replace('K-3/', 'K-3-')
    .replace('K-12/', 'K-12-')
    .replace('Е-', 'E-')
    .replace('Н-', 'N-')
    .replace('П-', 'P-')
    .replace('Т-', 'T-')
    .replace('Х-', 'X-')
    .replace('А-', 'A-')
  if (t.match(/^T-\d+\/\d+$/)) return t.replace('/', '-')
  if (t.match(/^A-\d+\/\d+$/)) return t.replace('/', '-')
  if (t === 'AVZ-1' || t === 'AVZ-2') return 'AVZ-12'
  if (t === 'AVZ-4' || t === 'AVZ-5') return 'AVZ-45'
  if (t === 'N-6X') return 'N-6x'
  if (t === 'E-44K') return 'E-44k'
  if (t === 'S-1K') return 'S-1k'
  if (t === 'SM-1K') return 'Sm-1k'
  if (t === 'HV-15K') return 'HV-15k'
  if (t === 'HV-30K') return 'HV-30k'
  if (t === 'HV-31K') return 'HV-31k'
  if (t === 'N-110K') return 'N-110k'
  if (t === 'N-111K') return 'N-111k'
  if (t === 'X-25K') return 'X-25K'
  if (t === 'E-1K') return 'E-1K'
  if (t === 'T-1K') return 'T-1K'
  return t
}

